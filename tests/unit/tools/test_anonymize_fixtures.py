def test_hostkey_fingerprints_keep_their_format_class() -> None:
    ctx = Anonymizer()
    assert ctx.hostkey_fingerprint(
        "SHA256:Qk9HVVMQk9HVVMQk9HVVMQk9HVVMQk9HVVMQk9HVVMQ"
    ) == synthetic_sha256_fingerprint(1)
    assert ctx.hostkey_fingerprint("0a:1b:2c:3d:4e:5f:60:71:82:93:a4:b5:c6:d7:e8:f9") == synthetic_md5_fingerprint(2)
    assert ctx.hostkey_fingerprint("\n") == "\n" and ctx.hostkey_fingerprint("") == ""
    with pytest.raises(ValueError, match="unknown host key fingerprint format"):
        ctx.hostkey_fingerprint("MD5:00")


def test_mapper_rejects_malformed_identifiers_and_address_exhaustion() -> None:
    ctx = Anonymizer()
    with pytest.raises(ValueError, match="expected a MAC address"):
        ctx.mac("not-a-mac")
    with pytest.raises(ValueError, match="expected a 24-hex object id"):
        ctx.object_id("short")
    with pytest.raises(ValueError, match="expected an IPv4 address"):
        ctx.ip("fe80::1")
    for n in range(254):
        ctx.ip(f"10.0.{n // 256}.{n % 256}")
    with pytest.raises(ValueError, match="more than 254"):
        ctx.ip("10.0.1.0")


def test_text_outside_the_closed_rules_fails_the_run_naming_the_path() -> None:
    with pytest.raises(
        tool.SpecError, match=r"^stat_device.json \$\.data\[0\]\.radio_table\[0\]\.radio: expected one of"
    ) as exc:
        anonymize({"stat_device.json": {"data": [{"type": "uap", "radio_table": [{"radio": "wifi7"}]}]}})
    assert "wifi7" not in str(exc.value)
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.model: expected a model code"):
        anonymize({"stat_device.json": {"data": [{"type": "usw", "model": "https://controller.example"}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.model: expected a model code"):
        anonymize({"stat_device.json": {"data": [{"type": "usw", "model": "U6LITE https://evil.example"}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.radio_table\[0\]\.ht: expected a channel width"):
        anonymize({"stat_device.json": {"data": [{"type": "uap", "radio_table": [{"ht": "80\n"}]}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.satisfaction: expected a non-text scalar"):
        anonymize({"stat_device.json": {"data": [{"type": "uap", "satisfaction": "hunter2"}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.channels_ng\[1\]: expected a channel number"):
        anonymize({"rest_setting.json": {"data": [{"key": "radio_ai", "channels_ng": ["1", "auto"]}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.key: expected one of the allowed values"):
        anonymize({"rest_setting.json": {"data": [{"key": "hunter2"}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.channels_na\[1\]: expected a channel number"):
        anonymize(
            {"rest_setting.json": {"data": [{"key": "radio_ai", "channels_na": ["36", "40 https://evil.example"]}]}}
        )
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.model: expected a model code"):
        anonymize({"stat_device.json": {"data": [{"type": "usw", "model": "F492BF123456"}]}})
    for address in ("192.168.1.10", "10.1.2.3", "1.1.1.1", "255.255.255.255", "10.0.0.254", "10.0.0.10"):
        with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.version: expected a firmware version"):
            anonymize({"stat_device.json": {"data": [{"type": "uap", "version": address}]}})
    for serial in ("F492BF123456", "F492BF1234567", "A" * 13):
        with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.model: expected a model code"):
            anonymize({"stat_device.json": {"data": [{"type": "usw", "model": serial}]}})
    for phone in ("0151 2345678", "0049 151 234 567 89", "0 5 * *", "030 12 34 56 78", "1-234 * * * *", "0 3 * * * *"):
        with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.cron_expr: expected a cron expression"):
            anonymize({"rest_setting.json": {"data": [{"key": "radio_ai", "cron_expr": phone}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.vap_table\[0\]\.state: expected one of"):
        anonymize({"stat_device.json": {"data": [{"type": "uap", "vap_table": [{"state": "SN12345"}]}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.channels_ng\[0\]: expected a channel number"):
        anonymize({"rest_setting.json": {"data": [{"key": "radio_ai", "channels_ng": ["12345"]}]}})
    with pytest.raises(
        tool.SpecError, match=r"\$\.data\[0\]\.minrate_ng_advertising_rates: expected a non-text scalar"
    ) as exc:
        anonymize({"list_wlanconf.json": {"data": [{"minrate_ng_advertising_rates": ["juergen"]}]}})
    assert "juergen" not in str(exc.value)
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.satisfaction: expected a non-text scalar"):
        anonymize({"stat_device.json": {"data": [{"type": "uap", "satisfaction": [1, 2]}]}})
    with pytest.raises(tool.SpecError, match=r"\$\.data\[0\]\.radio_table_stats\[0\]\.state: expected one of"):
        anonymize({"stat_device.json": {"data": [{"type": "uap", "radio_table_stats": [{"state": "SN12345"}]}]}})


