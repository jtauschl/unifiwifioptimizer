def test_identifiers_are_rewritten_consistently_across_endpoints() -> None:
    fixtures, dropped = anonymize(live_payloads())
    devices = fixtures["stat_device.json"]
    assert isinstance(devices, dict)
    switch, ap = devices["data"]
    assert switch == {"type": "usw", "mac": "02:00:00:00:00:01", "model": "USL8LP"}
    assert ap["mac"] == "02:00:00:00:00:02" and ap["name"] == "AP-1" and ap["ip"] == "192.0.2.1"
    assert ap["uplink"] == {"type": "wire", "mac": "02:00:00:00:00:02", "uplink_mac": "02:00:00:00:00:01"}
    assert ap["vap_table"][0] == {
        "radio": "ng",
        "bssid": "02:00:00:00:00:03",
        "essid": "SSID-1",
        "wlanconf_id": ap["_id"],
    }
    assert ap["radio_table"][0]["min_rssi"] is None
    assert fixtures["apgroups.json"] == [
        {"_id": "0" * 23 + "2", "name": "Group-1", "device_macs": ["02:00:00:00:00:02"]}
    ]
    clients = fixtures["stat_sta.json"]
    assert isinstance(clients, dict)
    assert clients["data"] == [
        {"is_wired": False, "ap_mac": "02:00:00:00:00:02", "essid": "SSID-1", "signal": -60},
        {"is_wired": True},
    ]
    assert dropped["hostname"] == 2 and dropped["x_passphrase"] == 1 and dropped["serial"] == 1 and dropped["mac"] == 2


